const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const base = require("./connaissances.json");
const { entreesVerifiees, repondreFAQ } = require("./connaissances");
test("base publique : provenance vérifiée, références stables et refus d’une source privée/périmée", () => {
  assert.equal(entreesVerifiees().length, base.entrees.length);
  assert.equal(new Set(base.entrees.map(e => e.id)).size, base.entrees.length);
  assert.equal(entreesVerifiees(() => "source modifiée").length, 0);
  assert.deepEqual(entreesVerifiees(() => { throw Error("Ne doit pas lire de fichier privé"); }, [{ provenance: [{ fichier: "../.env" }] }]), []);
  assert.match(repondreFAQ("Quels sont vos horaires ?").content, /mardi au samedi/);
  assert.match(repondreFAQ("What are your opening hours?").content, /Tuesday to Saturday/);
  assert.equal(repondreFAQ("Quelles sont vos conditions d’annulation ?").informationsManquantes, true);
  assert.ok(repondreFAQ("Sous quel délai aurai-je mon devis ?").sources.some(s => s.id === "devis-delai"));
  assert.match(repondreFAQ("Sous quel délai aurai-je mon devis ?").content, /48 h ouvrées/);
  assert.doesNotMatch(repondreFAQ("Sous quel délai aurai-je mon devis ?").content, /24 heures/);
  assert.match(repondreFAQ("Quels sont vos prix ?").content, /indicatifs/);
  assert.doesNotMatch(repondreFAQ("Quels sont vos prix ?").content, /179|148/);
  assert.equal(repondreFAQ("Quel est le chiffre d’affaires de Détour ?").informationsManquantes, true);
  assert.equal(repondreFAQ("Je préfère un voyage tranquille"), null);
  assert.equal(repondreFAQ("Merci pour votre réponse"), null);
  assert.equal(repondreFAQ("Je préfère voyager en train"), null);
  assert.match(repondreFAQ("Quel transport propose votre agence ?").content, /aller-retour depuis Paris/);
});
